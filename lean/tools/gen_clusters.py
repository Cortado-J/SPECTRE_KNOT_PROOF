#!/usr/bin/env python3
"""Write SpectreKnot/Data/Clusters.lean (the nine level-1 supertiles at tile level) and Data/Level2.lean (the
level-2 supertiles at tile level, for tests), computed in exact arithmetic by paper/code/exact/exact.py.

Level 1: for each kind, the tiles in the order of exact.py's tile_placements (the children in the order of Table 1,
the Mystic's two tiles last), which edges of which tiles are glued, the rim as a list of tile edges in the
supertile's own orientation starting at its vertex 0, and the rim positions of its six vertices (vertex 0 is the
first vertex at or after the crossover corner A, as in the paper).

Level 2 (tests only): the tile-level gluing of each level-2 supertile, built directly from the tile placements, and
its rim length and vertex positions. Lean's Statement.super 2 must reproduce it.

usage: python3 tools/gen_clusters.py   (from lean/)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'paper', 'code', 'exact'))
import exact as X  # noqa: E402

lev, trs_all = X.build(5)


def tile_gluing(gs):
    """glue[t][i] = (t', j) if edge e_i of tile t is edge e_j of tile t' (traversed oppositely), else None."""
    edges = {}
    verts = []
    for t, g in enumerate(gs):
        V = [X.iapply(g, v) for v in X.PTS]
        verts.append(V)
        for i in range(14):
            p, q = V[i], V[(i + 1) % 14]
            edges.setdefault((min(p, q), max(p, q)), []).append((t, i, p, q))
    glue = [[None] * 14 for _ in gs]
    for lst in edges.values():
        assert len(lst) <= 2, 'edge of three tiles'
        if len(lst) == 2:
            (t1, i, p1, q1), (t2, j, p2, q2) = lst
            assert p1 == q2 and q1 == p2, 'shared edge not traversed oppositely'
            glue[t1][i] = (t2, j)
            glue[t2][j] = (t1, i)
    return glue, edges


def rim_and_vertices(K, m):
    b = lev[m][K]
    VERT, _ = X.find_vertices(lev, trs_all, m, 5 - m)
    rel = VERT[K]
    assert len(rel) == 6, f'{K} level {m}: {rel}'
    i0 = (rel[0] + b.defA) % b.E
    vtx = [(r + b.defA - i0) % b.E for r in rel] + [b.E]
    assert vtx == sorted(vtx) and vtx[0] == 0
    return b, i0, vtx


def lean_opt(x):
    return 'none' if x is None else f'some ({x[0]}, {x[1]})'


def lean_glue(glue):
    return '[' + ', '.join('[' + ', '.join(lean_opt(x) for x in row) + ']' for row in glue) + ']'


out1 = ['/-',
        'GENERATED by tools/gen_clusters.py from paper/code/exact/exact.py (exact arithmetic). Do not edit by hand.',
        '-/',
        'import SpectreKnot.Basic',
        '',
        'namespace SpectreKnot.Clusters',
        '',
        'open Kind',
        '']
tiles, glues, rims, vtxs = {}, {}, {}, {}
for K in X.NAMES:
    gs = X.tile_placements(K, 1, X.ID, trs_all)
    glue, edges = tile_gluing(gs)
    b, i0, vtx = rim_and_vertices(K, 1)
    rim = []
    for k in range(b.E):
        p, q = b.verts[(i0 + k) % b.E], b.verts[(i0 + k + 1) % b.E]
        lst = edges[(min(p, q), max(p, q))]
        assert len(lst) == 1, 'rim edge shared'
        rim.append((lst[0][0], lst[0][1]))
    tiles[K], glues[K], rims[K], vtxs[K] = len(gs), glue, rim, vtx
    print(f'{K}: {len(gs)} tiles, rim {b.E}, vertices {vtx}')

out1 += ['/-- The number of tiles of the level-1 supertile of each kind. -/', 'def tiles : Kind → Nat']
out1 += [f'  | .{K} => {tiles[K]}' for K in X.NAMES]
out1 += ['', '/-- `glue K` lists, for each tile and each of its edges `e_0 … e_13`, the tile and edge it is glued to inside',
         'the level-1 supertile of kind `K`, or `none` for a rim edge. -/', 'def glue : Kind → List (List (Option (Nat × Nat)))']
out1 += [f'  | .{K} => {lean_glue(glues[K])}' for K in X.NAMES]
out1 += ['', '/-- The rim of the level-1 supertile as tile edges `(tile, i)`, in its own orientation, from its vertex 0. -/',
         'def rim : Kind → List (Nat × Nat)']
out1 += [f"  | .{K} => [{', '.join(f'({t}, {i})' for t, i in rims[K])}]" for K in X.NAMES]
out1 += ['', '/-- The rim positions of the vertices 0 … 5 of the level-1 supertile, and its rim length. -/',
         'def vtx : Kind → List Nat']
out1 += [f"  | .{K} => [{', '.join(map(str, vtxs[K]))}]" for K in X.NAMES]
out1 += ['', 'end SpectreKnot.Clusters', '']
open(os.path.join(HERE, '..', 'SpectreKnot', 'Data', 'Clusters.lean'), 'w').write('\n'.join(out1))

out2 = ['/-',
        'GENERATED by tools/gen_clusters.py from paper/code/exact/exact.py (exact arithmetic). Do not edit by hand.',
        'The level-2 supertiles at tile level, built directly from the tile placements: used only by Tests.lean.',
        '-/',
        'import SpectreKnot.Basic',
        '',
        'namespace SpectreKnot.Level2',
        '',
        'open Kind',
        '']
g2, v2 = {}, {}
for K in X.NAMES:
    gs = X.tile_placements(K, 2, X.ID, trs_all)
    g2[K], _ = tile_gluing(gs)
    _, _, v2[K] = rim_and_vertices(K, 2)
    print(f'level 2 {K}: {len(gs)} tiles, vertices {v2[K]}')
out2 += ['def glue : Kind → List (List (Option (Nat × Nat)))']
out2 += [f'  | .{K} => {lean_glue(g2[K])}' for K in X.NAMES]
out2 += ['', 'def vtx : Kind → List Nat']
out2 += [f"  | .{K} => [{', '.join(map(str, v2[K]))}]" for K in X.NAMES]
out2 += ['', 'end SpectreKnot.Level2', '']
open(os.path.join(HERE, '..', 'SpectreKnot', 'Data', 'Level2.lean'), 'w').write('\n'.join(out2))
print('wrote Data/Clusters.lean and Data/Level2.lean')
