#!/usr/bin/env python3
"""Write SpectreKnot/Data/Pattern.lean: the composition pattern C (paper Tables 1-3), the letters (Table 4),
the level-1 side lengths and the level-1 Sigma offset d_1.

Source: paper/code/hierarchy/combin_8.json (written by combin.js, stage A04 of paper/code/run_all.sh) and
letters.json (letters.py, A07). The pattern is the one extracted from the composition 1 -> 2; the script checks that
the compositions 2 -> 3 and 3 -> 4 in the same file are identical.

usage: python3 tools/gen_pattern.py   (from lean/)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'paper', 'code', 'hierarchy')
OUT = os.path.join(HERE, '..', 'SpectreKnot', 'Data', 'Pattern.lean')

J = json.load(open(os.path.join(SRC, 'combin_8.json')))
LT = json.load(open(os.path.join(SRC, 'letters.json')))
NAMES = ['Gamma', 'Delta', 'Theta', 'Lambda', 'Xi', 'Pi', 'Sigma', 'Phi', 'Psi']
ST = J['ST']['1']
for lev in J['ST']:   # pdef (the parent's corner A) moves with the level: d_m; everything else must agree
    for t in NAMES:
        for k in ('kids', 'sides', 'pside'):
            assert J['ST'][lev][t][k] == ST[t][k], f'pattern of level {lev} differs from level 1 ({t} {k})'


def piece(s):
    c, j = s.split('.')
    return f'({int(c)}, {int(j)})'


def lean_list(xs):
    return '[' + ', '.join(xs) + ']'


lines = [
    '/-',
    'GENERATED by tools/gen_pattern.py from paper/code/hierarchy/combin_8.json and letters.json. Do not edit by hand.',
    '-/',
    'import SpectreKnot.Basic',
    '',
    'namespace SpectreKnot.Pattern',
    '',
    'open Kind Letter',
    '',
    '/-- Paper Table 1: the kinds of the children of a supertile of each kind, child 0 first. -/',
    'def kids : Kind → List Kind',
]
for t in NAMES:
    lines.append(f'  | .{t} => {lean_list("." + k for k in ST[t]["kids"])}')
lines += [
    '',
    '/-- Paper Table 2: for child `c` and side `j`, `some (c\', j\')` if side `j` of child `c` is side `j\'` of child',
    '`c\'`, and `none` if it lies on the parent\'s rim. -/',
    'def adj : Kind → List (List (Option (Nat × Nat)))',
]
for t in NAMES:
    rows = [lean_list('none' if x == 'R' else f'some {piece(x)}' for x in row) for row in ST[t]['sides']]
    lines.append(f'  | .{t} => {lean_list(rows)}')
lines += [
    '',
    '/-- Paper Table 3: side `J` of the parent is the concatenation of the children\'s sides `(c, j)` listed, in the',
    'parent\'s own order. -/',
    'def pside : Kind → List (List (Nat × Nat))',
]
for t in NAMES:
    rows = [lean_list(piece(x) for x in side) for side in ST[t]['pside']]
    lines.append(f'  | .{t} => {lean_list(rows)}')
lines += [
    '',
    '/-- Paper Table 4: the letter of side `j` of a supertile of each kind. -/',
    'def letters : Kind → List Letter',
]
for t in NAMES:
    lines.append(f'  | .{t} => {lean_list("." + x for x in LT["letter"][t])}')
lines += [
    '',
    '/-- The side lengths of the level-1 supertiles, counted on the actual tiles (paper §6, `exact/exact.py`). -/',
    'def len1 : Kind → List Nat',
]
for t in NAMES:
    lines.append(f'  | .{t} => {lean_list(str(x) for x in J["LEN"]["1"][t])}')
d = J['DEF']['1']['Sigma']
assert d['side'] == 5
lines += [
    '',
    '/-- The level-1 Σ-supertile\'s crossover corner lies on its side 5, at this distance from vertex 5 (Lemma 6.4). -/',
    f'def d1 : Nat := {d["off"]}',
    '',
    'end SpectreKnot.Pattern',
    '',
]
open(OUT, 'w').write('\n'.join(lines))
print('wrote', os.path.relpath(OUT))
