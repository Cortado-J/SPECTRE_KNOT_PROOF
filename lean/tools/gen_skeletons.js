// Write SpectreKnot/Data/Skeletons.lean: the 18 skeletons S_T(l_1, d_1, w) of paper Computation 7.5, as built by
// paper/code/hierarchy/synth.js (function F) from the composition pattern C and the level-1 lengths. These are the
// objects that paper/code/hierarchy/induction.js checks; the Lean file re-runs that check in the kernel.
// Also writes, for each skeleton, the pairing that the JavaScript reduced walk (core/reduce.js rcompose) finds at the
// parent's crossover corners, so that the Lean walk can be compared with it.
//
// usage: node tools/gen_skeletons.js   (from lean/)
const fs = require('fs');
const path = require('path');
const HIER = path.join(__dirname, '..', '..', 'paper', 'code', 'hierarchy');
const { F } = require(path.join(HIER, 'synth.js'));
const { R, NAMES } = require(path.join(HIER, 'lib.js'));
const J = JSON.parse(fs.readFileSync(path.join(HIER, 'combin_8.json')));
const L1 = J.LEN[1], d1 = J.DEF[1].Sigma.off;

const out = [
  '/-',
  'GENERATED by tools/gen_skeletons.js from paper/code/hierarchy/synth.js (F) with the level-1 lengths. Do not edit.',
  '-/',
  'import SpectreKnot.Skeleton',
  '',
  'namespace SpectreKnot.Skeletons',
  '',
  'open Skeleton',
  '',
];
const names = [];
for (const w of [-1, 1]) {
  for (const T of NAMES) {
    const rd = F(T, null, 0, w, L1, d1);
    const rc = R.rcompose(rd);
    const kids = rd.kids.map((k) => {
      const runs = k.runs.map((r) => `⟨${r.len}, ${r.nb < 0 ? 'none' : `some (${r.partner[0]}, ${r.partner[1]})`}⟩`);
      return `{ runs := [${runs.join(', ')}], marks := [${k.markIds.join(', ')}], defA := ${k.defA}, defB := ${k.defB} }`;
    });
    const nm = `${T.toLowerCase()}${w > 0 ? 'Plus' : 'Minus'}`;
    names.push(nm);
    out.push(`/-- S_${T}(ℓ₁, d₁, ${w > 0 ? '+1' : '-1'}): ${rd.kids.length} children, ${rd.nMarks} marks, ` +
      `${rd.kids.reduce((a, k) => a + k.runs.length, 0)} runs, ${rd.rim.length} rim runs. JavaScript reduced walk: ` +
      `${rc.loops} loops, non-hooks at rim marks ${JSON.stringify(rc.nonHook)}. -/`);
    out.push(`def ${nm} : Skel where`);
    out.push(`  kids := [`);
    kids.forEach((k, i) => out.push(`    ${k}${i < kids.length - 1 ? ',' : ''}`));
    out.push(`  ]`);
    out.push(`  rim := [${rd.rim.map(([c, i]) => `(${c}, ${i})`).join(', ')}]`);
    out.push(`  omega := ${w > 0 ? 'true' : 'false'}`);
    out.push('');
    // JS results for comparison: rim indices of the non-hooks
    out.push(`def ${nm}JsNonHooks : List Nat := [${rc.nonHook.join(', ')}]`);
    out.push('');
  }
}
out.push('/-- All 18 skeletons, ω = -1 first. -/');
out.push(`def all : List Skel := [${names.join(', ')}]`);
out.push('');
out.push('/-- The non-hooks found by the JavaScript reduced walk, in the same order. -/');
out.push(`def allJsNonHooks : List (List Nat) := [${names.map((n) => n + 'JsNonHooks').join(', ')}]`);
out.push('');
out.push('end SpectreKnot.Skeletons');
out.push('');
const dst = path.join(__dirname, '..', 'SpectreKnot', 'Data', 'Skeletons.lean');
fs.writeFileSync(dst, out.join('\n'));
console.log('wrote', path.relative(process.cwd(), dst));
